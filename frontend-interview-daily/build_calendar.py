#!/usr/bin/env python3
"""生成报告归档日历页 report/calendar.html。

扫描 out/ 目录下已生成的每日 Markdown，渲染成一张按日期倒序的日历，
每格显示日期、星期、题量与方向数，点击进入当天的 HTML 报告。

用法:
    python3 build_calendar.py
"""
import datetime as dt
import json
import os
import re
from html import escape

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "out")
REPORT_DIR = os.path.join(HERE, "report")
STATE_FILE = os.path.join(HERE, "data", "state.json")

WEEK = "一二三四五六日"


def collect():
    days = []
    for name in sorted(os.listdir(OUT_DIR), reverse=True):
        if not name.endswith(".md"):
            continue
        date = name[:-3]
        try:
            day = dt.date.fromisoformat(date)
        except ValueError:
            continue
        text = open(os.path.join(OUT_DIR, name), encoding="utf-8").read()
        total = len(re.findall(r"https://www\.mianshiya\.com/question/", text))
        dirs = len(re.findall(r"^## ", text, re.M))
        days.append({
            "date": date,
            "weekday": "星期" + WEEK[day.weekday()],
            "total": total,
            "directions": dirs,
            "has_html": os.path.exists(os.path.join(REPORT_DIR, f"{date}.html")),
        })
    return days


def render(days):
    cards = []
    for d in days:
        href = f"./{d['date']}.html" if d["has_html"] else f"./{d['date']}.html"
        cards.append(
            f'<a class="day{" today" if d["date"] == dt.date.today().isoformat() else ""}" href="{href}">'
            f'<span class="dnum">{d["date"][5:]}</span>'
            f'<span class="dmeta">{d["weekday"]}</span>'
            f'<span class="dstat">{d["total"]} 题 · {d["directions"]} 方向</span>'
            f'</a>'
        )
    body = "\n".join(cards)
    return f"""<!-- Generated by Trae Work -->
<!DOCTYPE html>
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>每日前端面试题 · 归档</title>
<link rel="stylesheet" href="./assets/styles.css">
<style>
.cal-grid {{
  display: grid;
  grid-template-columns: repeat(auto-fill, minmax(150px, 1fr));
  gap: 12px;
  margin-top: 24px;
}}
.day {{
  display: flex;
  flex-direction: column;
  gap: 2px;
  padding: 14px 16px;
  border: 1px solid var(--rule);
  border-radius: 10px;
  background: var(--bg2);
  color: var(--ink);
  text-decoration: none;
  transition: border-color .18s ease, transform .18s ease, background .18s ease;
}}
.day:hover {{ border-color: var(--accent); background: var(--bg3); transform: translateY(-2px); }}
.day.today {{ border-color: var(--accent2); }}
.dnum {{ font-family: "DMMono", ui-monospace, monospace; font-size: 20px; color: var(--accent); }}
.day.today .dnum {{ color: var(--accent2); }}
.dmeta {{ font-size: 12px; color: var(--muted); }}
.dstat {{ font-size: 12px; color: var(--muted); }}
</style>
</head>
<body>
<div class="wrap">
  <header class="hero">
    <p class="kicker">Daily Frontend Interview · 面试鸭题库</p>
    <h1>每日前端面试题归档<span class="day">{len(days)} 期</span></h1>
    <p class="lede">按日期倒序排列，每期覆盖 <strong>16</strong> 个前端技术方向、每个方向 <strong>2</strong> 道题，题目在 30 天内基本不重复。</p>
  </header>

  <section class="sec">
    <h2>往期回顾</h2>
    <p class="sub">点击任意日期进入当天的题目清单。</p>
    <div class="cal-grid">
{body}
    </div>
  </section>

  <footer>
    <div class="sources">
      <h2>Sources</h2>
      <ol>
        <li id="cite-1">
          <span class="src-title">面试鸭 mianshiya.com，前端面试题库。题目标题、标签、难度与浏览量数据来源。</span>
          <a class="src-url" href="https://www.mianshiya.com" target="_blank" rel="noopener">https://www.mianshiya.com</a>
        </li>
        <li id="cite-2">
          <span class="src-title">面试鸭题库公开检索接口 api.mianshiya.com/api/question/search。</span>
          <a class="src-url" href="https://api.mianshiya.com" target="_blank" rel="noopener">https://api.mianshiya.com</a>
        </li>
      </ol>
    </div>
    <p class="note">本页由 <code>build_calendar.py</code> 生成</p>
  </footer>
</div>
</body>
</html>
"""


def main():
    days = collect()
    html = render(days)
    for name in ("calendar.html", "index.html"):
        path = os.path.join(REPORT_DIR, name)
        with open(path, "w", encoding="utf-8") as fp:
            fp.write(html)
    print(f"已生成 report/calendar.html 与 report/index.html（{len(days)} 期）")


if __name__ == "__main__":
    main()
